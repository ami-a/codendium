def test_build_is_blocked_by_an_unresolved_credential(make_tree, settings_for):
    settings = settings_for(make_tree({"a.py": 'KEY = "AKIAIOSFODNN7EXAMPLE"\n'}))
    result = Pipeline().build(settings)
    assert result.blocked_by
    assert not result.outputs


def test_force_overrides_the_block(make_tree, settings_for):
    settings = settings_for(make_tree({"a.py": 'KEY = "AKIAIOSFODNN7EXAMPLE"\n'}))
    result = Pipeline().build(settings, force=True)
    assert result.outputs


def test_acknowledging_a_finding_unblocks_the_build(make_tree, settings_for):
    settings = settings_for(make_tree({"a.py": 'KEY = "AKIAIOSFODNN7EXAMPLE"\n'}))
    pipeline = Pipeline()
    estimate = pipeline.estimate(settings)
    settings.scan.ignored_findings = [f.id for f in estimate.scan.secrets]
    result = pipeline.build(settings)
    assert not result.blocked_by
    assert result.outputs


def test_redacting_a_credential_still_blocks_until_acknowledged(make_tree, settings_for):
    """Blacking it out changes the PDF, not the fact that it is in the source."""
    settings = settings_for(make_tree({"a.py": 'KEY = "AKIAIOSFODNN7EXAMPLE"\n'}))
    settings.redaction.enabled = True
    settings.redaction.manual_lines = ["a.py:1"]
    result = Pipeline().build(settings)
    assert result.blocked_by
