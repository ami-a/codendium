def test_foreign_copyright_holder_is_flagged():
    source = "# Copyright (c) 2019 Some Other Company\nx = 1\n"
    findings = thirdparty.scan_text("a.py", comment_lines(source), "Test Owner")
    assert any(f.rule == "foreign-copyright" for f in findings)


def test_the_declared_owner_is_not_flagged():
    source = "# Copyright (c) 2026 Test Owner. All rights reserved.\nx = 1\n"
    findings = thirdparty.scan_text("a.py", comment_lines(source), "Test Owner")
    assert not any(f.rule == "foreign-copyright" for f in findings)


def test_corporate_suffixes_do_not_defeat_owner_matching():
    source = "# Copyright (c) 2026 Acme Inc.\nx = 1\n"
    findings = thirdparty.scan_text("a.py", comment_lines(source), "Acme")
    assert not any(f.rule == "foreign-copyright" for f in findings)


def test_the_word_copyright_in_prose_is_not_a_notice():
    source = '"""Handles copyright registration for the copyright owner."""\nx = 1\n'
    findings = thirdparty.scan_text("a.py", comment_lines(source), "Test Owner")
    assert not any(f.rule == "foreign-copyright" for f in findings)


def test_copyright_inside_code_is_never_seen():
    source = 'MESSAGE = "Copyright (c) 2019 Someone Else"\nx = 1\n'
    findings = thirdparty.scan_text("a.py", comment_lines(source), "Test Owner")
    assert not any(f.rule == "foreign-copyright" for f in findings)


def test_spdx_identifier_is_reported():
    source = "# SPDX-License-Identifier: Apache-2.0\nx = 1\n"
    findings = thirdparty.scan_text("a.py", comment_lines(source), "Test Owner")
    assert any(f.rule == "spdx-license" for f in findings)


def test_generated_file_marker_is_reported():
    source = "# Code generated by protoc. DO NOT EDIT.\nx = 1\n"
    findings = thirdparty.scan_text("a.py", comment_lines(source), "Test Owner")
    assert any(f.rule == "generated-file" for f in findings)


def test_vendored_path_is_reported():
    findings = thirdparty.scan_text("third_party/lib/a.py", [""], "Test Owner")
    assert any(f.rule == "vendored-path" for f in findings)


